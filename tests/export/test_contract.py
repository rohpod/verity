"""The contract: schema from the models, types from the schema, both committed (ADR 0029,
decision 12). The TypeScript step needs Node, so CI regenerates it and fails on a difference;
here the schema is compared directly and the types are checked for shape."""

import json
import re
import sys

import yaml
from export_support import AS_OF, ROOT, built_fixture
from jsonschema import Draft202012Validator
from verity_core.export.build import serialise

GENERATED = ROOT / "web" / "generated"
SCHEMA = GENERATED / "snapshot.schema.json"
TYPES = GENERATED / "snapshot.ts"
CI = ROOT / ".github" / "workflows" / "ci.yml"


def script():
    sys.path.insert(0, str(ROOT / "scripts"))
    try:
        import generate_snapshot_contract as module
    finally:
        sys.path.pop(0)
    return module


def test_the_committed_schema_is_the_one_the_models_give():
    assert SCHEMA.read_text(encoding="utf-8") == script().schema_text()


def test_a_snapshot_validates_against_the_committed_schema():
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    Draft202012Validator.check_schema(schema)
    document = json.loads(serialise(built_fixture(AS_OF).snapshot))
    errors = list(Draft202012Validator(schema).iter_errors(document))
    assert errors == []


def test_a_field_the_schema_does_not_list_does_not_validate():
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    document = json.loads(serialise(built_fixture(AS_OF).snapshot))
    resource = next(n for n in document["nodes"] if n["type"] == "AWSResource")
    resource["config_hash"] = "a" * 64
    errors = list(Draft202012Validator(schema).iter_errors(document))
    assert errors, "a withheld field must not validate"


def test_a_snapshot_missing_a_required_part_does_not_validate():
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    document = json.loads(serialise(built_fixture(AS_OF).snapshot))
    del document["header"]["as_of"]
    assert list(Draft202012Validator(schema).iter_errors(document))


def test_the_types_name_every_snapshot_model_in_the_schema():
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    text = TYPES.read_text(encoding="utf-8")
    assert "export interface Snapshot " in text
    assert "automatically generated by json-schema-to-typescript" in text
    missing = [name for name in schema["$defs"] if not re.search(rf"\b{re.escape(name)}\b", text)]
    assert missing == []


def test_the_generated_types_hold_no_account_url_or_path():
    from verity_core.export import scan

    assert scan.scan_text(json.dumps({"ts": TYPES.read_text(), "schema": SCHEMA.read_text()})) == []


def test_the_schema_step_does_not_need_node():
    module = script()
    assert module.schema_text().endswith("\n") and module.write_types


# --- web/ stays minimal, and CI regenerates the contract ---------------------------------


def test_web_holds_only_what_type_generation_needs():
    package = json.loads((ROOT / "web" / "package.json").read_text())
    assert package["devDependencies"] == {"json-schema-to-typescript": "16.0.0"}
    assert set(package) <= {"name", "private", "description", "devDependencies"}
    assert not (ROOT / "web" / "src").exists()  # M10 owns the rest of web/
    lock = json.loads((ROOT / "web" / "package-lock.json").read_text())
    assert lock["packages"]["node_modules/json-schema-to-typescript"]["version"] == "16.0.0"


def test_no_dependency_version_in_web_floats():
    package = json.loads((ROOT / "web" / "package.json").read_text())
    for version in package["devDependencies"].values():
        assert re.fullmatch(r"\d+\.\d+\.\d+", version), version


def test_node_modules_is_ignored_by_git():
    assert "node_modules/" in (ROOT / ".gitignore").read_text()


def steps():
    return yaml.safe_load(CI.read_text())["jobs"]["check"]["steps"]


def test_ci_pins_setup_node_and_installs_from_the_lockfile():
    uses = [s["uses"] for s in steps() if "uses" in s]
    assert any(re.fullmatch(r"actions/setup-node@v\d+\.\d+\.\d+", u) for u in uses)
    runs = [s["run"] for s in steps() if "run" in s]
    assert any("npm ci" in r and "--prefix web" in r for r in runs)


def test_ci_regenerates_the_contract_and_fails_on_a_difference():
    runs = [s["run"] for s in steps() if "run" in s]
    generate = next(i for i, r in enumerate(runs) if "generate_snapshot_contract.py" in r)
    check = next(
        i for i, r in enumerate(runs) if "git status --porcelain" in r and "web/generated" in r
    )
    assert generate < check


def test_ci_scans_a_committed_snapshot():
    runs = " ".join(s["run"] for s in steps() if "run" in s)
    assert "verity export --check web/public/data/snapshot.json" in runs


def test_ci_holds_no_aws_credentials():
    text = CI.read_text()
    assert "configure-aws-credentials" not in text and "AWS_" not in text
    assert "secrets." not in text
    assert yaml.safe_load(text)["permissions"] == {"contents": "read"}


def test_dependabot_watches_web():
    config = yaml.safe_load((ROOT / ".github" / "dependabot.yml").read_text())
    assert {"package-ecosystem": "npm", "directory": "/web"}.items() <= next(
        u for u in config["updates"] if u["package-ecosystem"] == "npm"
    ).items()
